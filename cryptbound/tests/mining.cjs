assert.equal(M.upgradeTenth(boosted).ok,true);
assert.equal(boosted.materials['Рунная руда'],0);
assert.equal(boosted.mining.level,10);assert.equal(M.damagePct(boosted),10);
assert.equal(M.upgradeTenth(boosted).ok,false,'level max');
assert.equal(M.ORES[M.rollVein(1,fixed(.99))].id,'steel');
assert.equal(M.ORES[M.rollVein(24,fixed(.99))].id,'rune');
assert.equal(M.ORES[M.newVein(24,fixed(.99)).type].id,'rune');
assert.equal(M.isOreName('Рунная руда'),true);
assert.equal(M.isOreName('Старая шестерёнка'),false);
assert.equal(M.houseCost(0)['Железная руда'],5);
const house={'Железная руда':5};assert.equal(M.canBuild(house,0),true);
assert.equal(M.build(house,0),true);assert.equal(house['Железная руда'],0);
assert.equal(M.canBuild(house,1),false);
const persisted=JSON.parse(JSON.stringify(hero));
assert.equal(M.nodeLevel(persisted,'doubleOre'),5,'tree survives JSON save/load');
assert.equal(M.pickItem(persisted).id,1234);
persisted.locationIndex=2;assert.equal(M.active(persisted),false,'only mountain location active');
assert.equal(M.harvest(persisted,{kind:'ore-vein',revealed:true,mine:{type:0,hp:2}},fixed(.99),0).ok,false);
console.log('OK: mountain mining: 4 ores, 18 nodes ×5, equipment, mining turns, level ten, city recipes, persistence');
