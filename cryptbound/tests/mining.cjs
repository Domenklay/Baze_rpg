/* Mining rules: deterministic economy, six 3-node rays, combat-only equipped bonuses, T1-2 save stability. */
'use strict';
const assert=require('node:assert/strict'),vm=require('node:vm'),fs=require('node:fs'),path=require('node:path');
const ctx={window:{}};vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(__dirname,'../src/main/assets/mining.js'),'utf8'),ctx,{filename:'mining.js'});
const M=ctx.window.CryptMining;
function run(){return {actIndex:0,locationIndex:1,floor:1,materials:{},items:[],equip:{weapon:null}};}
function fixed(x){return ()=>x;}
function supply(r,num){for(const ore of M.ORES)r.materials[ore.name]=num;}
assert.equal(M.ORES.length,4,'exactly four mineral rarities');
assert.equal(M.BRANCHES.length,6,'six spokes');
assert(M.BRANCHES.every(b=>b.nodes.length===3),'three nodes per spoke');
assert.equal(new Set(M.BRANCHES.flatMap(b=>b.nodes.map(n=>n[0]))).size,18,'unique nodes');
assert.deepEqual(JSON.parse(JSON.stringify(M.BRANCHES[0].nodes.map(n=>n[1]))),['Меткость','Шанс крита','Критический урон']);
const hero=run(),item=M.grantPick(hero,1234);
assert.equal(hero.items.length,1);assert.equal(item.slot,'weapon');assert.equal(item.miningPick,true);
assert.equal(hero.equip.weapon,1234);assert.equal(M.grantPick(hero,456).id,1234,'no duplicate pick');
assert.equal(M.damagePct(hero),1,'first level +1% damage');
assert.equal(M.miningPower(hero),1);
assert.equal(M.nodeLevel(hero,'accuracy'),0);
assert.equal(M.cost(hero,'accuracy')['Железная руда'],1,'opening one ore');
assert.equal(M.canUpgrade(hero,'critChance').ok,false,'sequential unlocking');
assert.equal(M.upgradeNode(hero,'accuracy').ok,false,'insufficient ore');
supply(hero,1000);
assert.equal(M.upgradeNode(hero,'accuracy').ok,true);
assert.equal(M.nodeLevel(hero,'accuracy'),1);
assert.equal(M.cost(hero,'accuracy')['Железная руда'],2);
assert.equal(M.bonus(hero,'accuracy'),3);
assert.equal(M.canUpgrade(hero,'critChance').ok,true);
assert.equal(M.upgradeNode(hero,'critChance').ok,true);
assert.equal(M.canUpgrade(hero,'critDamage').ok,true);
assert.equal(M.cost(hero,'critDamage')['Кварцевая руда'],1);
assert.equal(M.upgradeNode(hero,'critDamage').ok,true);
for(const branch of M.BRANCHES)for(const node of branch.nodes){
 const id=node[0];while(M.nodeLevel(hero,id)<5)assert.equal(M.upgradeNode(hero,id).ok,true,'can level '+id);
 assert.equal(M.nodeLevel(hero,id),5);
 assert.equal(M.canUpgrade(hero,id).ok,false,'level cap '+id);
}
assert.equal(Object.keys(hero.mining.nodes).length,18);
assert.equal(M.bonus(hero,'critChance'),10);assert.equal(M.bonus(hero,'doubleHit'),10);assert.equal(M.bonus(hero,'flatDamage'),10);
const spare={id:2222,slot:'weapon',atk:10};hero.items.push(spare);hero.equip.weapon=2222;
assert.equal(M.bonus(hero,'flatDamage'),0,'not equipped => no combat bonuses');
assert.equal(M.damagePct(hero),0,'not equipped => no +damage%');
hero.equip.weapon=1234;
assert.equal(M.damagePct(hero),16,'5 levels of damage% + level1');
const empty=run();M.grantPick(empty,99);
let tile={kind:'ore-vein',revealed:false,cleared:false,mine:{type:0,hp:2}};
assert.equal(M.harvest(empty,tile,fixed(.99),0).ok,false,'cannot mine unopened tile');
tile.revealed=true;
assert.equal(M.harvest(empty,tile,fixed(.99),0).finished,false,'one hit reduces durability');
assert.equal(tile.mine.hp,1);
let result=M.harvest(empty,tile,fixed(.99),0);
assert.equal(result.finished,true);assert.equal(result.ore,'Железная руда');
assert.equal(result.qty,1);assert.equal(empty.materials['Железная руда'],1);
assert.equal(empty.mining.xp,1);assert.equal(tile.cleared,true);
assert.equal(M.harvest(empty,tile,fixed(.99),0).ok,false,'no repeatable mining');
empty.equip.weapon=null;tile={kind:'ore-vein',revealed:true,cleared:false,mine:{type:0,hp:2}};
assert.equal(M.harvest(empty,tile,fixed(.99),0).ok,false,'requires equipped pick');
empty.equip.weapon=99;
let strong={kind:'ore-vein',revealed:true,cleared:false,mine:{type:3,hp:14}};
assert.equal(M.harvest(empty,strong,fixed(.99),0).ok,false,'rune vein mining-level gate');
assert(M.XP[10]>M.XP[9]);
let boosted=run();M.grantPick(boosted,33);
M.gainXP(boosted,1000);
assert.equal(boosted.mining.level,9,'level ten cannot be automated');
assert.equal(M.levelReady(boosted),true);
assert.equal(M.upgradeTenth(boosted).ok,false,'rune ore required for level 10');
